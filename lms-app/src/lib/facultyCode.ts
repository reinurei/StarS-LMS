import { isSupabaseConfigured, supabase } from './supabaseClient';

const CHARSET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // Avoids ambiguous characters like O/0, I/1
const FACULTY_CODES_STORAGE_KEY = 'lms_faculty_access_codes_v1';

export interface FacultyCode {
  code: string;
  created_at: string;
  expires_at: string | null;
  is_used: boolean;
  used_by_email?: string | null;
  used_at?: string | null;
  notes?: string;
}

/**
 * Generates a cryptographically random faculty admin code in format PROF-XXXX-XXXX
 */
export function generateRandomFacultyCodeString(): string {
  const getRandomPart = (len: number) => {
    const array = new Uint32Array(len);
    if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
      crypto.getRandomValues(array);
    } else {
      for (let i = 0; i < len; i++) {
        array[i] = Math.floor(Math.random() * 0xffffffff);
      }
    }
    let res = '';
    for (let i = 0; i < len; i++) {
      res += CHARSET[array[i] % CHARSET.length];
    }
    return res;
  };

  return `PROF-${getRandomPart(4)}-${getRandomPart(4)}`;
}

export function loadLocalFacultyCodes(): FacultyCode[] {
  try {
    const raw = localStorage.getItem(FACULTY_CODES_STORAGE_KEY);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch {
    // ignore
  }
  const initial: FacultyCode[] = [
    {
      code: 'PROF-8K2N-9X4M',
      created_at: new Date().toISOString(),
      expires_at: null,
      is_used: false,
      notes: 'Initial Demo Faculty Code',
    },
  ];
  saveLocalFacultyCodes(initial);
  return initial;
}

export function saveLocalFacultyCodes(codes: FacultyCode[]): void {
  try {
    localStorage.setItem(FACULTY_CODES_STORAGE_KEY, JSON.stringify(codes));
  } catch {
    // ignore
  }
}

/**
 * Generates and saves a new random faculty admin code
 */
export async function createFacultyCode(notes?: string): Promise<FacultyCode> {
  const code = generateRandomFacultyCodeString();
  const now = new Date();
  const expiresAt = new Date(now.getTime() + 7 * 24 * 60 * 60 * 1000).toISOString();
  const nowIso = now.toISOString();

  let createdCode: FacultyCode | null = null;

  if (isSupabaseConfigured) {
    try {
      // 1. Try SQL function first
      const { data: rpcCode, error: rpcError } = await supabase.rpc('generate_random_faculty_code', {
        notes_text: notes ?? 'Generated by Admin',
      });

      if (!rpcError && rpcCode) {
        createdCode = {
          code: rpcCode,
          created_at: nowIso,
          expires_at: expiresAt,
          is_used: false,
          notes: notes ?? 'Generated by Admin',
        };
      } else {
        // 2. Direct table insert fallback
        const { data: { session } } = await supabase.auth.getSession();
        const { data, error } = await supabase
          .from('faculty_access_codes')
          .insert({
            code,
            created_by: session?.user?.id ?? null,
            expires_at: expiresAt,
            is_used: false,
            notes: notes ?? 'Generated by Faculty Admin',
          })
          .select()
          .single();

        if (!error && data) {
          createdCode = data as FacultyCode;
        } else if (error) {
          console.warn('Direct Supabase insert failed:', error.message);
        }
      }
    } catch (err) {
      console.warn('Supabase code creation error:', err);
    }
  }

  // Always keep a local copy as well
  const fallbackCode: FacultyCode = createdCode ?? {
    code,
    created_at: nowIso,
    expires_at: expiresAt,
    is_used: false,
    notes: notes ?? 'Generated by Faculty Admin',
  };

  const localCodes = loadLocalFacultyCodes();
  localCodes.unshift(fallbackCode);
  saveLocalFacultyCodes(localCodes);
  return fallbackCode;
}

/**
 * Lists all active or generated faculty codes
 */
export async function listFacultyCodes(): Promise<FacultyCode[]> {
  if (isSupabaseConfigured) {
    try {
      const { data, error } = await supabase
        .from('faculty_access_codes')
        .select('*')
        .order('created_at', { ascending: false });
      if (!error && data && data.length > 0) {
        return data as FacultyCode[];
      }
    } catch {
      // Fallback
    }
  }
  return loadLocalFacultyCodes();
}

/**
 * Validates and consumes a random faculty code during registration
 */
export async function validateAndConsumeFacultyCode(
  rawInputCode: string,
  userEmail: string,
): Promise<{ valid: boolean; error?: string }> {
  const normalized = rawInputCode.trim().toUpperCase();
  if (!normalized) {
    return {
      valid: false,
      error: 'A Faculty Admin Code is required to register as Professor.',
    };
  }

  const now = new Date();

  if (isSupabaseConfigured) {
    try {
      // 1. Try secure RPC function first (bypasses RLS issues)
      const { data: rpcRes, error: rpcErr } = await supabase.rpc('verify_and_consume_faculty_code', {
        code_input: normalized,
        email_input: userEmail.toLowerCase(),
      });

      if (!rpcErr && rpcRes) {
        if (rpcRes.valid) {
          return { valid: true };
        }
        return { valid: false, error: rpcRes.error ?? 'Invalid Faculty Admin Code.' };
      }

      // 2. Direct table check fallback
      const { data, error } = await supabase
        .from('faculty_access_codes')
        .select('*')
        .eq('code', normalized)
        .maybeSingle();

      if (!error && data) {
        const codeRecord = data as FacultyCode;
        if (codeRecord.is_used) {
          return { valid: false, error: 'This Faculty Admin Code has already been used.' };
        }
        if (codeRecord.expires_at && new Date(codeRecord.expires_at) < now) {
          return { valid: false, error: 'This Faculty Admin Code has expired.' };
        }

        // Mark as used
        await supabase
          .from('faculty_access_codes')
          .update({
            is_used: true,
            used_by_email: userEmail.toLowerCase(),
            used_at: now.toISOString(),
          })
          .eq('code', normalized);

        return { valid: true };
      }
    } catch (err) {
      console.warn('Supabase code validation error:', err);
    }
  }

  // Check in local demo store
  const codes = loadLocalFacultyCodes();
  const match = codes.find((c) => c.code.toUpperCase() === normalized);
  if (!match) {
    return {
      valid: false,
      error: 'Invalid Faculty Admin Code. Please check the code provided by your administrator.',
    };
  }
  if (match.is_used) {
    return { valid: false, error: 'This Faculty Admin Code has already been used.' };
  }
  if (match.expires_at && new Date(match.expires_at) < now) {
    return { valid: false, error: 'This Faculty Admin Code has expired.' };
  }

  match.is_used = true;
  match.used_by_email = userEmail.toLowerCase();
  match.used_at = now.toISOString();
  saveLocalFacultyCodes(codes);
  return { valid: true };
}

/**
 * Retrieves the latest active demo code for display assistance
 */
export function getLatestActiveFacultyCode(): string | null {
  const codes = loadLocalFacultyCodes();
  const active = codes.find((c) => !c.is_used && (!c.expires_at || new Date(c.expires_at) > new Date()));
  return active ? active.code : null;
}
